"""Extract real document text and visual inputs; never invent attachment contents."""

import json
import math
import mimetypes
import os
import subprocess
import zipfile
from pathlib import Path

from fastapi import HTTPException, UploadFile
from PIL import Image, ImageOps, UnidentifiedImageError

from .chat_storage import ChatStore, identifier, now
from .config import Settings
from .knowledge_ingestion import DocumentExtractionError, extract_document_text
from .media_ingest import (
    MediaValidationError,
    _ffmpeg_executable,
    probe_media,
    run_captured_process,
    safe_filename,
    validate_upload_header,
)
from .media_security import MalwareScanError, scan_media_file

MAX_ATTACHMENT_BYTES = 50 * 1024 * 1024
MAX_USER_BYTES = 2 * 1024 * 1024 * 1024
MAX_DOCUMENT_CHARS = 60000
SUPPORTED_EXTENSIONS = [
    ".txt",
    ".md",
    ".markdown",
    ".docx",
    ".doc",
    ".pdf",
    ".jpg",
    ".jpeg",
    ".png",
    ".webp",
    ".mp4",
    ".mov",
    ".m4v",
    ".webm",
    ".mkv",
]


def attachment_directory(store: ChatStore, attachment_id: str) -> Path:
    # IDs are generated by the server or obtained from an ownership-checked row.
    if len(attachment_id) != 32 or any(char not in "0123456789abcdef" for char in attachment_id):
        raise HTTPException(404, "附件不存在")
    return store.root / "attachments" / attachment_id


def image_for_model(source: Path, destination: Path) -> None:
    try:
        with Image.open(source) as image:
            if image.width * image.height > 20_000_000:
                raise ValueError("图片超过 2000 万像素，请缩小后上传")
            image.load()
            prepared = ImageOps.exif_transpose(image).convert("RGB")
            prepared.thumbnail((1600, 1600))
            prepared.save(destination, "JPEG", quality=85)
    except (UnidentifiedImageError, Image.DecompressionBombError, OSError):
        raise ValueError("图片无法解码，请上传有效的 JPG、PNG 或 WebP 图片") from None


def document_text(source: Path) -> str:
    if source.suffix == ".doc":
        from .chat_office import extract_legacy_doc

        text = extract_legacy_doc(source)
        if len(text) > MAX_DOCUMENT_CHARS:
            raise ValueError("文档文字超过 6 万字，请拆分后上传")
        if "\x00" in text:
            raise ValueError("DOC 正文包含无效字符，请检查文件格式")
        return text
    if source.suffix == ".docx":
        try:
            with zipfile.ZipFile(source) as archive:
                members = archive.infolist()
                if (
                    len(members) > 10000
                    or sum(item.file_size for item in members) > 64 * 1024 * 1024
                ):
                    raise ValueError("DOCX 解压后内容过大，请拆分文档")
        except zipfile.BadZipFile:
            raise ValueError("DOCX 文件格式无效") from None
    if source.suffix == ".pdf":
        from pypdf import PdfReader

        try:
            reader = PdfReader(source)
            if reader.is_encrypted:
                raise ValueError("请先解密 PDF 后上传")
            if len(reader.pages) > 200:
                raise ValueError("PDF 超过 200 页，请拆分后上传")
        except ValueError:
            raise
        except Exception:
            raise ValueError("PDF 文件格式无效") from None
    try:
        text = extract_document_text(source, max_bytes=MAX_ATTACHMENT_BYTES)
    except DocumentExtractionError as exc:
        if source.suffix == ".pdf" and "未提取" in str(exc):
            raise ValueError(
                "PDF 未包含可提取文字；扫描版请先进行 OCR，或将页面作为图片上传给支持视觉的模型"
            ) from None
        raise ValueError(str(exc)) from None
    if len(text) > MAX_DOCUMENT_CHARS:
        raise ValueError("文档文字超过 6 万字，请拆分后上传")
    if "\x00" in text:
        raise ValueError("文本文件包含二进制内容，请检查文件格式")
    return text


def video_frames(source: Path, directory: Path, settings: Settings, mime_type: str) -> dict:
    probe = probe_media(source, kind="video", media_type=mime_type, timeout_seconds=30)
    duration = probe.duration_seconds
    if duration is None or not math.isfinite(duration) or duration <= 0 or duration > 1800:
        raise ValueError("无法读取视频时长或视频超过 30 分钟，请拆分后上传")
    executable = _ffmpeg_executable(settings.ffmpeg_path)
    if not executable:
        raise ValueError("服务器未安装视频解析组件，请联系管理员")
    count = min(6, max(1, math.ceil(duration)))
    timestamps = [round(duration * (index + 0.5) / count, 3) for index in range(count)]
    for index, timestamp in enumerate(timestamps):
        frame = directory / f"frame-{index}.jpg"
        completed = run_captured_process(
            [
                executable,
                "-hide_banner",
                "-loglevel",
                "error",
                "-nostdin",
                "-y",
                "-ss",
                str(timestamp),
                "-i",
                str(source),
                "-map",
                "0:v:0",
                "-frames:v",
                "1",
                "-vf",
                "scale=1024:1024:force_original_aspect_ratio=decrease",
                "-q:v",
                "3",
                str(frame),
            ],
            timeout=30,
        )
        if completed.returncode != 0 or not frame.exists():
            raise ValueError("视频关键帧无法解码，请重新导出为 MP4 后上传")
        image_for_model(frame, frame)
    return {
        "duration_seconds": duration,
        "frame_count": count,
        "timestamps": timestamps,
        "notice": "依据时序关键帧识别画面，不包含音轨内容",
    }


def store_upload(store: ChatStore, settings: Settings, owner: str, upload: UploadFile) -> dict:
    name = safe_filename(upload.filename)
    suffix = Path(name).suffix.lower()
    if suffix not in SUPPORTED_EXTENSIONS:
        raise HTTPException(422, "支持 TXT、Markdown、DOC、DOCX、PDF、JPG、PNG、WebP 和常见视频格式")
    aid = identifier()
    directory = attachment_directory(store, aid)
    directory.mkdir(parents=True, mode=0o700)
    source = directory / ("original" + suffix)
    size = 0
    try:
        with source.open("wb") as stream:
            if os.name != "nt":
                os.chmod(source, 0o600)
            while chunk := upload.file.read(1024 * 1024):
                size += len(chunk)
                if size > MAX_ATTACHMENT_BYTES:
                    raise ValueError("单个附件不能超过 50 MB")
                stream.write(chunk)
        if size == 0:
            raise ValueError("附件不能为空")
        scan_media_file(
            source,
            command=settings.antivirus_command,
            timeout_seconds=settings.antivirus_timeout_seconds,
            required=settings.antivirus_required,
        )
        if suffix in {".txt", ".md", ".markdown", ".doc", ".docx", ".pdf"}:
            kind = "document"
            text = document_text(source)
            mime_type = mimetypes.guess_type(name)[0] or "text/plain"
            metadata = {"text": text, "text_preview": text[:240]}
        else:
            with source.open("rb") as stream:
                head = stream.read(128 * 1024)
            kind, mime_type = validate_upload_header(
                filename=name, declared_media_type=upload.content_type, head=head, size_bytes=size
            )
            if kind == "image":
                image_for_model(source, directory / "analysis.jpg")
                metadata = {}
            else:
                metadata = video_frames(source, directory, settings, mime_type)
        metadata["suffix"] = suffix
        with store.connect(write=True) as connection:
            used, count = connection.execute(
                "SELECT COALESCE(SUM(size),0),COUNT(*) FROM attachments WHERE owner=?", (owner,)
            ).fetchone()
            if used + size > MAX_USER_BYTES or count >= 2000:
                raise ValueError("AI 对话附件空间已满，请删除旧对话或附件")
            connection.execute(
                "INSERT INTO attachments(id,owner,conversation_id,name,kind,mime_type,size,created_at,metadata_json) VALUES(?,?,?,?,?,?,?,?,?)",
                (
                    aid,
                    owner,
                    None,
                    name,
                    kind,
                    mime_type,
                    size,
                    now(),
                    json.dumps(metadata, ensure_ascii=False),
                ),
            )
            row = store.attachment(connection, aid, owner)
            result = store.attachment_document(row)
        return result
    except (ValueError, MediaValidationError, MalwareScanError) as exc:
        raise HTTPException(422, str(exc)) from None
    except (OSError, RuntimeError, subprocess.TimeoutExpired):
        raise HTTPException(503, "附件处理失败，请检查服务器存储和解析组件后重试") from None
    finally:
        # Failed uploads never leave potentially sensitive orphan files behind.
        if not locals().get("result"):
            remove_attachment_directory(store, aid)


def remove_attachment_directory(store: ChatStore, attachment_id: str) -> None:
    import shutil

    directory = attachment_directory(store, attachment_id)
    if directory.exists():
        if not directory.resolve().is_relative_to((store.root / "attachments").resolve()):
            raise HTTPException(503, "附件存储路径无效，请联系管理员")
        try:
            shutil.rmtree(directory)
        except OSError:
            raise HTTPException(503, "附件清理失败，请检查服务器存储后重试") from None
